//! The `CustomerIntegration` resource (SPEC §7): one customer's channel, mapping and credentials,
//! and what the operator reports back in its status.
//!
//! The CRD in `deploy/helm/pourline/crds/` is generated from these types (`operator crd`), and a
//! test fails if the two drift apart. Its CEL rules reject an inconsistent spec at `kubectl apply`.

use chrono::{DateTime, Utc};
use kube::{CustomResource, KubeSchema};
use schemars::JsonSchema;
use serde::{Deserialize, Serialize};

/// The finalizer that stops an integration's workload before the resource goes away.
pub const FINALIZER: &str = "pourline.dev/cleanup";

/// How the customer's system reaches us.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "lowercase")]
pub enum Channel {
    Webhook,
    Sftp,
}

impl Channel {
    pub fn as_str(self) -> &'static str {
        match self {
            Channel::Webhook => "webhook",
            Channel::Sftp => "sftp",
        }
    }
}

/// What to run. The resource's name is the integration's, as in `customers/<name>/`.
#[derive(CustomResource, KubeSchema, Debug, Clone, PartialEq, Serialize, Deserialize)]
#[kube(
    group = "pourline.dev",
    version = "v1alpha1",
    kind = "CustomerIntegration",
    namespaced,
    doc = "A customer integration that the Pourline operator runs as its own ingest workload",
    status = "CustomerIntegrationStatus",
    printcolumn = r#"{"name":"Channel","type":"string","jsonPath":".spec.channel"}"#,
    printcolumn = r#"{"name":"Phase","type":"string","jsonPath":".status.phase"}"#,
    printcolumn = r#"{"name":"Dead letters","type":"integer","jsonPath":".status.deadLetterCount"}"#,
    printcolumn = r#"{"name":"Last ingest","type":"date","jsonPath":".status.lastSuccessfulIngest"}"#,
    printcolumn = r#"{"name":"Age","type":"date","jsonPath":".metadata.creationTimestamp"}"#
)]
#[x_kube(validation = Rule::new("self.channel == 'sftp' ? has(self.schedule) : !has(self.schedule)").message("an sftp integration needs a schedule, and a webhook integration takes none"))]
#[x_kube(validation = Rule::new("self.channel == 'webhook' || self.replicas == 1").message("an sftp integration polls with one replica: two would race to move the same files"))]
#[serde(rename_all = "camelCase")]
pub struct CustomerIntegrationSpec {
    /// Must match the mapping's own `channel`. It can't change: delete and re-create the
    /// integration instead.
    #[x_kube(validation = Rule::new("self == oldSelf").message("the channel can't change: delete the integration and create it again"))]
    pub channel: Channel,
    /// The ConfigMap with the integration's `mapping.yaml`.
    pub mapping_config_map: String,
    /// The Secret with the credentials: `token` for a webhook, `username` and `password` for sftp.
    pub credentials_secret: String,
    /// When to poll, as a cron expression. Required for sftp, not allowed for a webhook.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub schedule: Option<String>,
    /// Webhook pods. An sftp integration runs one poll at a time.
    #[serde(default = "one")]
    #[schemars(range(min = 1))]
    pub replicas: i32,
    /// Stops the integration without deleting it: no webhook pods, no polls.
    #[serde(default)]
    pub paused: bool,
}

fn one() -> i32 {
    1
}

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub enum Phase {
    /// Applied, not ready yet.
    #[default]
    Pending,
    Running,
    Paused,
    /// See `message`.
    Failed,
}

#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "camelCase")]
pub struct CustomerIntegrationStatus {
    pub phase: Phase,
    /// Why, whenever the phase isn't `Running`, or a problem reading the status.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub message: Option<String>,
    /// The last delivery in which a record was published or recognised as a duplicate.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub last_successful_ingest: Option<DateTime<Utc>>,
    /// Dead letters waiting for a replay (`ingest-cli dlq replay`).
    #[serde(default)]
    pub dead_letter_count: u64,
}

/// The CRD as the chart ships it, in `deploy/helm/pourline/crds/`.
pub fn crd_yaml() -> Result<String, serde_saphyr::ser::Error> {
    use kube::CustomResourceExt;
    let yaml = serde_saphyr::to_string(&CustomerIntegration::crd())?;
    Ok(format!(
        "# Generated by `cargo run -p operator -- crd` from crates/operator/src/crd.rs. Don't edit.\n{yaml}"
    ))
}

#[cfg(test)]
mod tests {
    #![allow(clippy::unwrap_used)]

    use std::path::Path;

    use kube::CustomResourceExt;

    use super::*;

    #[test]
    fn the_chart_ships_the_crd_these_types_generate() {
        let path = "deploy/helm/pourline/crds/customerintegrations.yaml";
        let file = Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../..")
            .join(path);
        let committed = std::fs::read_to_string(file).unwrap_or_default();
        assert!(
            committed == crd_yaml().unwrap(),
            "{path} is out of date: cargo run -p operator -- crd > {path}"
        );
    }

    #[test]
    fn the_crd_rejects_an_inconsistent_spec_and_shows_the_status_in_columns() {
        let crd = CustomerIntegration::crd();
        let version = &crd.spec.versions[0];
        let schema = version
            .schema
            .as_ref()
            .unwrap()
            .open_api_v3_schema
            .as_ref()
            .unwrap();
        let spec = &schema.properties.as_ref().unwrap()["spec"];
        let rules: Vec<&str> = spec
            .x_kubernetes_validations
            .as_ref()
            .unwrap()
            .iter()
            .map(|v| v.rule.as_str())
            .collect();
        assert_eq!(
            rules,
            [
                "self.channel == 'sftp' ? has(self.schedule) : !has(self.schedule)",
                "self.channel == 'webhook' || self.replicas == 1"
            ]
        );
        let columns: Vec<&str> = version
            .additional_printer_columns
            .as_ref()
            .unwrap()
            .iter()
            .map(|c| c.name.as_str())
            .collect();
        assert_eq!(
            columns,
            ["Channel", "Phase", "Dead letters", "Last ingest", "Age"]
        );
        assert!(version.subresources.as_ref().unwrap().status.is_some());
    }
}
